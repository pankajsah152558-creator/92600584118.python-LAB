
# 1. Iterating over a List
numbers = [10, 20, 30, 40, 50]

print("List Elements:")
for num in numbers:
    print(num)

# 2. Iterating over a String
text = "PYTHON"

print("\nString Characters:")
for ch in text:
    print(ch)

# 3. Iterating over a Dictionary
student = {
    "name": "Rahul",
    "age": 18,
    "course": "Python"
}

print("\nDictionary Elements:")
for key, value in student.items():
    print(key, ":", value)
